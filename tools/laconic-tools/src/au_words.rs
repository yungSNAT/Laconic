/// Python's `str.isspace` for one character: Unicode White_Space plus the 4 information
/// separators U+001C to U+001F, which Python also counts.
fn is_space(c: char) -> bool {
    c.is_whitespace() || ('\u{1c}'..='\u{1f}').contains(&c)
}

/// Python's `str.islower`: at least one cased character, and no uppercase or titlecase one.
fn is_lower(word: &str) -> bool {
    // The 31 titlecase letters (category Lt), which Rust's char API does not expose.
    let titlecase = |c: char| {
        matches!(
            c,
            '\u{1c5}' | '\u{1c8}' | '\u{1cb}' | '\u{1f2}' | '\u{1fbc}' | '\u{1fcc}' | '\u{1ffc}'
        ) || matches!(c, '\u{1f88}'..='\u{1f8f}' | '\u{1f98}'..='\u{1f9f}' | '\u{1fa8}'..='\u{1faf}')
    };
    let mut cased = false;
    for c in word.chars() {
        if c.is_uppercase() || titlecase(c) {
            return false;
        }
        cased |= c.is_lowercase();
    }
    cased
}

/// Python's `str.isalpha`, approximately.
// shortcut: Unicode Alphabetic, which also admits combining marks and letter numbers that
// Python's letters-only isalpha rejects. ESDB at 1e5b7d3a72 has no such character (only
// ASCII and Latin-1 letters); compare against a general-category table if a later ESDB does.
fn is_alpha(word: &str) -> bool {
    !word.is_empty() && word.chars().all(char::is_alphabetic)
}

/// Python's `str.splitlines` without line ends.
fn split_lines(text: &str) -> Vec<&str> {
    let mut lines = Vec::new();
    let mut start = 0;
    let mut chars = text.char_indices().peekable();
    while let Some((i, c)) = chars.next() {
        let end = match c {
            '\r' if chars.peek().is_some_and(|&(_, n)| n == '\n') => {
                chars.next();
                i + 2
            }
            '\n' | '\r' | '\u{b}' | '\u{c}' | '\u{1c}' | '\u{1d}' | '\u{1e}' | '\u{85}'
            | '\u{2028}' | '\u{2029}' => i + c.len_utf8(),
            _ => continue,
        };
        lines.push(&text[start..i]);
        start = end;
    }
    if start < text.len() {
        lines.push(&text[start..]);
    }
    lines
}

/// The text after stripping `chars` from the right, then from the left, as Python's
/// `rstrip("*-@~!†").lstrip("-@!")` does to every entry.
fn bare(word: &str) -> &str {
    word.trim_end_matches(['*', '-', '@', '~', '!', '†'])
        .trim_start_matches(['-', '@', '!'])
}

/// The lemma and its derived forms, in order; `None` marks an unusable slot.
fn words_of(lemma: &str, entries: &str) -> Vec<Option<String>> {
    let mut out = if lemma == "-" {
        vec![]
    } else {
        vec![Some(lemma.to_owned())]
    };
    let (mut depth, mut item, mut items) = (0i64, String::new(), Vec::new());
    for c in entries.chars() {
        depth += i64::from(c == '(');
        depth -= i64::from(c == ')');
        if c == ',' && depth == 0 {
            items.push(std::mem::take(&mut item));
        } else {
            item.push(c);
        }
    }
    if !item.trim_matches(is_space).is_empty() {
        items.push(item);
    }
    for item in &items {
        let mut item = item.trim_matches(is_space);
        if item.starts_with('(') {
            item = item.trim_matches(['(', ')']);
            item = item.split('|').next().unwrap_or("").trim_matches(is_space);
            if item.contains(':') {
                out.push(None);
                continue;
            }
        }
        let word = bare(item);
        out.push((!word.is_empty()).then(|| word.to_owned()));
    }
    out
}

/// Spelling choices inside one derived form, such as (A: labeled | B: labelled).
///
/// Each choice maps a spelling code to its word; "" marks an unmarked form. The groups are
/// those Python's `re.findall(r"\(([^()]*)\)")` found: a `(` whose next parenthesis is `)`.
fn inline_choices(entries: &str) -> Vec<HashMap<&str, &str>> {
    let mut choices = Vec::new();
    let mut open = None;
    for (i, c) in entries.char_indices() {
        match c {
            '(' => open = Some(i + 1),
            ')' => {
                if let Some(start) = open.take() {
                    let mut choice = HashMap::new();
                    for alt in entries[start..i].split('|') {
                        let alt = alt.trim_matches(is_space);
                        let (codes, word) = alt.rsplit_once(": ").unwrap_or(("", alt));
                        let word = bare(word);
                        let mut codes = codes.split(is_space).filter(|c| !c.is_empty()).peekable();
                        if codes.peek().is_none() {
                            choice.entry("").or_insert(word);
                        }
                        for code in codes {
                            choice.entry(code).or_insert(word);
                        }
                    }
                    choices.push(choice);
                }
            }
            _ => {}
        }
    }
    choices
}

/// One ESDB line: its variant tokens, size and the text after them, or `None` for a line
/// without a size field. A line whose tokens are not all variant codes keeps no tokens.
fn parse(line: &str) -> Option<(Vec<&str>, u64, &str)> {
    let (sizes, rest) = line.split_once(": ")?;
    // shortcut: ASCII digits only, where Python's `\d` and `int` also read other scripts'
    // decimal digits. ESDB at 1e5b7d3a72 writes every size in ASCII; read Unicode decimal
    // digits here if a later ESDB does not.
    let digits = sizes.len() - sizes.trim_start_matches(|c: char| c.is_ascii_digit()).len();
    // A run of digits fails to parse only when it overflows, which is above MAX_SIZE too.
    let size = if digits == 0 {
        99
    } else {
        sizes[..digits].parse().unwrap_or(u64::MAX)
    };
    let (head, tail) = rest.split_once(": ").unwrap_or((rest, ""));
    let tokens: Vec<&str> = head.split(is_space).filter(|t| !t.is_empty()).collect();
    let variant = |t: &&str| {
        let mut chars = t.chars();
        match (chars.next(), chars.next(), chars.next()) {
            (Some('+'), None, _) => true,
            (Some(first), second, None) => {
                "ABZCD_".contains(first) && second.is_none_or(|c| ".=?v~V-@x".contains(c))
            }
            _ => false,
        }
    };
    if tokens.is_empty() || !tokens.iter().all(variant) {
        return Some((vec![], size, rest));
    }
    Some((tokens, size, tail))
}

/// The lemma without its annotations (`<...>`, `{...}`, `(...)`) and the entries after
/// the first ": ".
fn lemma_and_entries(text: &str) -> (String, &str) {
    let (info, entries) = text.split_once(": ").unwrap_or((text, ""));
    let mut lemma = String::with_capacity(info.len());
    let mut missing = Vec::new();
    let mut index = 0;
    while let Some(c) = info[index..].chars().next() {
        let closer = match c {
            '<' => Some('>'),
            '{' => Some('}'),
            '(' => Some(')'),
            _ => None,
        };
        if let Some(closer) = closer.filter(|c| !missing.contains(c)) {
            if let Some(end) = info[index + 1..].find(closer) {
                while lemma.ends_with(is_space) {
                    lemma.pop();
                }
                index += 1 + end + 1;
                continue;
            }
            // A failed search covers the remaining suffix; never scan it again.
            missing.push(closer);
        }
        lemma.push(c);
        index += c.len_utf8();
    }
    let lemma = lemma.trim_matches(is_space);
    let lemma = if lemma == "-" {
        lemma
    } else {
        lemma.trim_start_matches(['-', '@', '!'])
    };
    (lemma.to_owned(), entries)
}

/// The groups of non-comment lines between blank lines, each line cut at " #".
fn groups(text: &str) -> Vec<Vec<&str>> {
    let mut groups = vec![];
    let mut group = vec![];
    for line in split_lines(text) {
        if line.trim_matches(is_space).is_empty() {
            if !group.is_empty() {
                groups.push(std::mem::take(&mut group));
            }
        } else if !line.starts_with('#') {
            group.push(line.split(" #").next().unwrap_or(line));
        }
    }
    if !group.is_empty() {
        groups.push(group);
    }
    groups
}

/// The kept pairs, sorted by US form, and the number of candidate pairs.
fn pairs(esdb: &str, manual: &str) -> (BTreeMap<String, String>, usize) {
    // Python dicts keep the first value set; `entry().or_insert` does the same.
    let mut found: HashMap<String, String> = HashMap::new();
    let mut au_valid: HashSet<String> = HashSet::new();
    let mut add_valid = |w: &str| {
        if is_lower(w) {
            au_valid.insert(w.to_owned());
        }
    };
    for group in groups(esdb) {
        let rows: Vec<_> = group.iter().filter_map(|line| parse(line)).collect();
        let has_d = rows
            .iter()
            .any(|(tokens, _, _)| tokens.iter().any(|t| t.starts_with('D')));
        let (mut us_rows, mut au_rows) = (vec![], vec![]);
        for (tokens, size, text) in rows {
            let tokens: Vec<String> = tokens
                .iter()
                .map(|t| match t.strip_prefix('B') {
                    Some(rest) if !has_d => format!("D{rest}"),
                    _ => (*t).to_owned(),
                })
                .collect();
            let (lemma, entries) = lemma_and_entries(text);
            let forms = words_of(&lemma, entries);
            if tokens.is_empty()
                || tokens
                    .iter()
                    .any(|t| matches!(t.as_str(), "D" | "D." | "D="))
            {
                forms.iter().flatten().for_each(|w| add_valid(w));
            }
            for choice in inline_choices(entries) {
                let au_form = match choice.get("D") {
                    Some(d) if !d.is_empty() => Some(*d),
                    Some(_) => None,
                    None => choice.get("B").copied(),
                }
                .filter(|w| !w.is_empty());
                for w in [choice.get("").copied(), au_form].into_iter().flatten() {
                    if !w.is_empty() {
                        add_valid(w);
                    }
                }
                let us_form = choice.get("A").copied().filter(|w| !w.is_empty());
                if let (Some(us), Some(au)) = (us_form, au_form)
                    && size <= MAX_SIZE
                    && us != au
                    && is_lower(us)
                    && is_lower(au)
                    && is_alpha(us)
                {
                    found.entry(us.to_owned()).or_insert_with(|| au.to_owned());
                }
            }
            let us = tokens.iter().any(|t| t == "A");
            let au = tokens.iter().any(|t| t == "D");
            if us && !au {
                us_rows.push((size, forms));
            } else if au && !us {
                au_rows.push((size, forms));
            }
        }
        for ((size, us_forms), (_, au_forms)) in us_rows.iter().zip(&au_rows) {
            if *size > MAX_SIZE || us_forms.len() != au_forms.len() {
                continue;
            }
            for (us, au) in us_forms.iter().zip(au_forms) {
                if let (Some(us), Some(au)) = (us, au)
                    && us != au
                    && is_lower(us)
                    && is_lower(au)
                    && is_alpha(us)
                {
                    found.entry(us.clone()).or_insert_with(|| au.clone());
                }
            }
        }
    }
    let manual = manual.to_lowercase();
    let manual_words: HashSet<&str> = manual
        .split(|c: char| !c.is_ascii_lowercase())
        .filter(|w| !w.is_empty())
        .collect();
    let candidates = found.len();
    let kept = found
        .into_iter()
        .filter(|(us, _)| {
            !au_valid.contains(us)
                && !KEEP.contains(&us.as_str())
                && !KEEP_PREFIXES.iter().any(|p| us.starts_with(p))
                && (!manual_words.contains(us.as_str()) || MANUAL_REJECTS.contains(&us.as_str()))
                && us.chars().count() >= 4
        })
        .collect();
    (kept, candidates)
}

/// Writes `OUT` under `root` from ESDB's scowl-pre.txt and the Style Manual's text.
pub fn run(root: &Path, esdb: &str, manual: &str) -> Result<String, String> {
    let read =
        |path: &str| fs::read_to_string(path).map_err(|e| format!("cannot read {path}: {e}"));
    let (kept, candidates) = pairs(&read(esdb)?, &read(manual)?);
    let mut out = String::from(HEADER);
    for (us, au) in &kept {
        out.push_str(&format!("{us} {au}\n"));
    }
    fs::write(root.join(OUT), out).map_err(|e| format!("cannot write {OUT}: {e}"))?;
    Ok(format!(
        "{candidates} candidate pairs, {} written to {OUT}",
        kept.len()
    ))
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::sync::mpsc;
    use std::time::Duration;

    #[test]
    fn annotation_removal_preserves_lemma_and_entries() {
        let cases = [
            ("word <n> {tag} (note): forms", ("word", "forms")),
            ("-@!word <n>", ("word", "")),
            ("-: forms", ("-", "forms")),
            ("<n> word: a: b", ("word", "a: b")),
            ("Croft Manor", ("Croft Manor", "")),
            ("a (b) c", ("a c", "")),
            ("a (b) (c)d", ("ad", "")),
            ("<outer<inner>>word", (">word", "")),
            ("x \t<missing {tag}: forms", ("x \t<missing", "forms")),
            ("x\u{2003}<tag>y", ("xy", "")),
            ("word <missing", ("word <missing", "")),
            ("word [kept]", ("word [kept]", "")),
        ];
        for (source, (lemma, entries)) in cases {
            let got = lemma_and_entries(source);
            assert_eq!(
                (got.0.as_str(), got.1),
                (lemma, entries),
                "source {source:?}"
            );
        }
    }

    #[test]
    fn long_non_annotations_finish_within_deadline() {
        // Run on a thread so a regression fails the test instead of hanging the runner.
        for repeated in [" ", "<", "({<"] {
            let text = format!("Croft{}Manor", repeated.repeat(200_000));
            let (send, receive) = mpsc::channel();
            let input = text.clone();
            std::thread::spawn(move || {
                let (lemma, entries) = lemma_and_entries(&input);
                let _ = send.send((lemma, entries.to_owned()));
            });
            let got = receive
                .recv_timeout(Duration::from_secs(5))
                .unwrap_or_else(|_| panic!("{repeated:?} repeated took over 5 seconds"));
            assert_eq!(got, (text, String::new()), "repeated {repeated:?}");
        }
    }
}
