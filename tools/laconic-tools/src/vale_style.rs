//! `laconic-tools vale-style [--check]`: writes `vale/Laconic/`, a Vale style generated from
//! `laconic-check`'s rule table and word lists, so a Vale user gets the rules a regular
//! expression can express. Each Vale rule is named after the `lint` rule it follows and links
//! to that rule's entry in `docs/rules.md`. Rules that need `lint`'s parsing (clauses,
//! paragraphs, the calendar or the whole document) are listed in `NOT_GENERATED` instead.
//! `vale/tests/` holds the fixtures that check the style against `lint`: this crate's tests
//! compare `lint` with the expected Vale output, and the `vale-style` workflow runs Vale.

use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

use laconic_check::lint::{self, RULES, RULES_URL};

/// The style's folder, from the repository root; its name is the style's name in Vale.
pub const STYLE_DIR: &str = "vale/Laconic";

